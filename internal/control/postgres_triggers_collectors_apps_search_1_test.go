// The collectors_apps_search_1 trigger lane ports the SQLite triggers on
// app_workspaces, collector_runtime, dashboards and search_history. Every
// identifier in this file carries the cas1 prefix because each trigger lane
// adds a file like this one to package control_test.
const (
	cas1Lane          = "collectors_apps_search_1"
	cas1MigrationFile = "0010_collectors_apps_search_1_triggers.sql"
	cas1FixturePath   = "testdata/postgres_triggers/collectors_apps_search_1.json"

	// cas1TriggerCount is the number of SQLite triggers on cas1Tables in the
	// final schema, each ported once.
	cas1TriggerCount = 23

	cas1ExpectAccept = "accept"
	cas1ExpectReject = "reject"
	// cas1RaiseSQLState is PL/pgSQL's default RAISE EXCEPTION SQLSTATE. A
	// reject scenario expects it unless the fixture names another code.
	cas1RaiseSQLState = "P0001"
)

// cas1OtherLanes are the trigger lanes a fixture case may depend on: every
// lane of the PostgreSQL trigger port except this one. A name outside this
// set is a typo that would keep its case pending forever.
var cas1OtherLanes = map[string]bool{
	"audit_1":                  true,
	"audit_2":                  true,
	"collectors_apps_search_2": true,
	"core_ingest_1":            true,
	"core_ingest_2":            true,
	"core_ingest_3":            true,
	"knowledge_catalog_1":      true,
	"knowledge_catalog_2":      true,
	"knowledge_objects_1":      true,
	"knowledge_objects_2":      true,
	"lookups":                  true,
}

// cas1Tables are the tables whose triggers this lane owns. No other lane
// creates a trigger on them.
var cas1Tables = []string{"app_workspaces", "collector_runtime", "dashboards", "search_history"}

// cas1Scenario is one differential case from the fixture. The fixture was
// generated by running every case against SQLite with the final schema and
// against PostgreSQL, so accept/reject and the message are SQLite's outcome.
type cas1Scenario struct {
	Name      string   `json:"name"`
	SetupSQL  []string `json:"setup_sql"`
	Statement string   `json:"statement"`
	Expect    string   `json:"expect"`
	Message   string   `json:"message"`
	// SQLState overrides cas1RaiseSQLState for a rejection that is not a
	// trigger RAISE, such as an arithmetic overflow inside a trigger.
	SQLState string `json:"sqlstate,omitempty"`
	// SQLiteMessage is set only on a PostgreSQL-specific case whose outcome
	// is a documented divergence: both engines reject, but SQLite reported
	// this message instead of Message.
	SQLiteMessage string `json:"sqlite_message,omitempty"`
	// DependsOnLanes lists other trigger lanes whose triggers must be
	// installed for the case to hold. Such cases run only in
	// TestPostgresCollectorsAppsSearch1CrossLaneTriggerScenarios.
	DependsOnLanes []string `json:"depends_on_lanes,omitempty"`
}

func cas1LoadScenarios(t *testing.T) []cas1Scenario {
	t.Helper()
	contents, err := os.ReadFile(cas1FixturePath)
	if err != nil {
		t.Fatalf("read trigger fixture: %v", err)
	}
	decoder := json.NewDecoder(bytes.NewReader(contents))
	decoder.DisallowUnknownFields()
	var scenarios []cas1Scenario
	if err := decoder.Decode(&scenarios); err != nil {
		t.Fatalf("decode trigger fixture: %v", err)
	}
	if len(scenarios) == 0 {
		t.Fatal("trigger fixture has no scenarios")
	}
	return scenarios
}

var cas1CreateTrigger = regexp.MustCompile(`(?m)^CREATE TRIGGER ([a-z0-9_]+)$`)

var cas1CreateFunction = regexp.MustCompile(`(?m)^CREATE FUNCTION ([a-z0-9_]+)\(\)$`)

var cas1TriggerLaneFile = regexp.MustCompile(`^\d{4}_([a-z0-9_]+)_triggers\.sql$`)

// cas1MigrationNames returns the trigger and function names the lane's
// migration creates, in file order.
func cas1MigrationNames(t *testing.T) (triggers, functions []string) {
	t.Helper()
	contents, err := fs.ReadFile(migrations.Postgres(), cas1MigrationFile)
	if err != nil {
		t.Fatalf("read embedded %s: %v", cas1MigrationFile, err)
	}
	for _, match := range cas1CreateTrigger.FindAllStringSubmatch(string(contents), -1) {
		triggers = append(triggers, match[1])
	}
	for _, match := range cas1CreateFunction.FindAllStringSubmatch(string(contents), -1) {
		functions = append(functions, match[1])
	}
	return triggers, functions
}

// cas1InstalledLanes returns the trigger lanes present in the embedded
// PostgreSQL migration set, keyed by lane name.
func cas1InstalledLanes(t *testing.T) map[string]bool {
	t.Helper()
	entries, err := fs.ReadDir(migrations.Postgres(), ".")
	if err != nil {
		t.Fatalf("read embedded PostgreSQL migrations: %v", err)
	}
	lanes := make(map[string]bool)
	for _, entry := range entries {
		if match := cas1TriggerLaneFile.FindStringSubmatch(entry.Name()); match != nil {
			lanes[match[1]] = true
		}
	}
	return lanes
}

func TestPostgresCollectorsAppsSearch1TriggerFixtureIsWellFormed(t *testing.T) {
	t.Parallel()

	scenarios := cas1LoadScenarios(t)
	triggers, _ := cas1MigrationNames(t)
	if len(triggers) != cas1TriggerCount {
		t.Fatalf("%s creates %d triggers, want %d: %v", cas1MigrationFile, len(triggers), cas1TriggerCount, triggers)
	}

	names := make(map[string]bool, len(scenarios))
	for index, scenario := range scenarios {
		label := fmt.Sprintf("scenario %d (%q)", index, scenario.Name)
		if strings.TrimSpace(scenario.Name) == "" || names[scenario.Name] {
			t.Errorf("%s: name is empty or duplicated", label)
		}
		names[scenario.Name] = true
		if strings.TrimSpace(scenario.Statement) == "" {
			t.Errorf("%s: statement is empty", label)
		}
		for setupIndex, statement := range scenario.SetupSQL {
			if strings.TrimSpace(statement) == "" {
				t.Errorf("%s: setup statement %d is empty", label, setupIndex)
			}
		}
		switch scenario.Expect {
		case cas1ExpectAccept:
			if scenario.Message != "" || scenario.SQLState != "" || scenario.SQLiteMessage != "" {
				t.Errorf("%s: an accepted statement carries no message, SQLSTATE or divergence", label)
			}
		case cas1ExpectReject:
			if scenario.Message == "" {
				t.Errorf("%s: a rejection needs its exact message", label)
			}
			if scenario.SQLState == cas1RaiseSQLState {
				t.Errorf("%s: sqlstate %s is the default and must be omitted", label, cas1RaiseSQLState)
			}
			if scenario.SQLiteMessage != "" && scenario.SQLiteMessage == scenario.Message {
				t.Errorf("%s: sqlite_message must differ from message", label)
			}
		default:
			t.Errorf("%s: expect = %q, want accept or reject", label, scenario.Expect)
		}
		for _, lane := range scenario.DependsOnLanes {
			if !cas1OtherLanes[lane] {
				t.Errorf("%s: depends_on_lanes names %q, which is not another trigger lane", label, lane)
			}
		}
	}

	// Every trigger needs a case that it rejects and one that it admits; a
	// case is attributed to the trigger its name starts with.
	for _, trigger := range triggers {
		var accepted, rejected bool
		for _, scenario := range scenarios {
			if !strings.HasPrefix(scenario.Name, trigger+" ") {
				continue
			}
			accepted = accepted || scenario.Expect == cas1ExpectAccept
			rejected = rejected || scenario.Expect == cas1ExpectReject
		}
		if !accepted || !rejected {
			t.Errorf("trigger %s: accepted case = %t, rejected case = %t, want both", trigger, accepted, rejected)
		}
	}
}

func TestPostgresCollectorsAppsSearch1TriggersAreInstalled(t *testing.T) {
	t.Parallel()

	db := testsupport.NewPostgresControlDB(t)
	ctx := t.Context()
	wantTriggers, wantFunctions := cas1MigrationNames(t)
	slices.Sort(wantTriggers)
	slices.Sort(wantFunctions)

	rows, err := db.SQLDB().QueryContext(ctx, `
		SELECT trigger.tgname, trigger.tgenabled, function.proname
		FROM pg_catalog.pg_trigger AS trigger
		JOIN pg_catalog.pg_class AS relation ON relation.oid = trigger.tgrelid
		JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = relation.relnamespace
		JOIN pg_catalog.pg_proc AS function ON function.oid = trigger.tgfoid
		WHERE namespace.nspname = $1
		  AND relation.relname::text = ANY (string_to_array($2, ','))
		  AND NOT trigger.tgisinternal
		ORDER BY trigger.tgname`,
		control.PostgresSchema,
		strings.Join(cas1Tables, ","),
	)
	if err != nil {
		t.Fatalf("list lane triggers: %v", err)
	}
	var gotTriggers []string
	functionSet := make(map[string]bool)
	for rows.Next() {
		var name, enabled, function string
		if err := rows.Scan(&name, &enabled, &function); err != nil {
			_ = rows.Close()
			t.Fatalf("scan lane trigger: %v", err)
		}
		if enabled != "O" {
			t.Errorf("trigger %s tgenabled = %q, want O (fires in origin mode only)", name, enabled)
		}
		gotTriggers = append(gotTriggers, name)
		functionSet[function] = true
	}
	if err := errors.Join(rows.Err(), rows.Close()); err != nil {
		t.Fatalf("list lane triggers: %v", err)
	}
	if !slices.Equal(gotTriggers, wantTriggers) {
		t.Fatalf("triggers on %v = %v, want %v", cas1Tables, gotTriggers, wantTriggers)
	}
	gotFunctions := make([]string, 0, len(functionSet))
	for function := range functionSet {
		gotFunctions = append(gotFunctions, function)
	}
	slices.Sort(gotFunctions)
	if !slices.Equal(gotFunctions, wantFunctions) {
		t.Fatalf("trigger functions = %v, want %v", gotFunctions, wantFunctions)
	}

	// Each function pins search_path, so its unqualified table names never
	// resolve through a caller's search_path.
	for _, function := range wantFunctions {
		var config string
		if err := db.SQLDB().QueryRowContext(ctx, `
			SELECT array_to_string(coalesce(function.proconfig, '{}'), ',')
			FROM pg_catalog.pg_proc AS function
			JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = function.pronamespace
			WHERE namespace.nspname = $1 AND function.proname = $2`,
			control.PostgresSchema,
			function,
		).Scan(&config); err != nil {
			t.Fatalf("read %s configuration: %v", function, err)
		}
		if config != "search_path="+control.PostgresSearchPath {
			t.Errorf("function %s proconfig = %q, want search_path=%s", function, config, control.PostgresSearchPath)
		}
	}
}

// cas1RunScenario runs one fixture case in its own transaction, which is
// always rolled back: setup, then the statement under test, compared with
// the expected outcome. Setup statements such as SET session_replication_role
// and ALTER TABLE ... DISABLE TRIGGER are transactional, so nothing leaks to
// the next case.
func cas1RunScenario(t *testing.T, db *sql.DB, scenario cas1Scenario) {
	t.Helper()
	ctx := t.Context()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatalf("begin scenario transaction: %v", err)
	}
	defer func() {
		if err := tx.Rollback(); err != nil {
			t.Errorf("roll back scenario transaction: %v", err)
		}
	}()
	if _, err := tx.ExecContext(ctx, `SET LOCAL search_path TO `+control.PostgresSchema); err != nil {
		t.Fatalf("pin scenario search_path: %v", err)
	}
	for index, statement := range scenario.SetupSQL {
		if _, err := tx.ExecContext(ctx, statement); err != nil {
			t.Fatalf("setup statement %d failed: %v\n%s", index, err, statement)
		}
	}

	_, err = tx.ExecContext(ctx, scenario.Statement)
	switch scenario.Expect {
	case cas1ExpectAccept:
		if err != nil {
			t.Fatalf("statement rejected, want accepted: %v\n%s", err, scenario.Statement)
		}
	case cas1ExpectReject:
		if err == nil {
			t.Fatalf("statement accepted, want rejected with %q\n%s", scenario.Message, scenario.Statement)
		}
		var pgErr *pgconn.PgError
		if !errors.As(err, &pgErr) {
			t.Fatalf("statement error %v is not a PostgreSQL error", err)
		}
		wantCode := scenario.SQLState
		if wantCode == "" {
			wantCode = cas1RaiseSQLState
		}
		if pgErr.Code != wantCode || pgErr.Message != scenario.Message {
			t.Fatalf(
				"statement error = %s %q, want %s %q",
				pgErr.Code,
				pgErr.Message,
				wantCode,
				scenario.Message,
			)
		}
		if wantCode == cas1RaiseSQLState {
			// Store code matches trigger text either exactly through
			// control.RaiseMessage or as a substring of err.Error() (for
			// example internal/dashboards); both must see the message.
			message, ok := control.RaiseMessage(err)
			if !ok || message != scenario.Message || !control.IsRaise(err) {
				t.Fatalf("RaiseMessage(err) = %q, %t; want %q", message, ok, scenario.Message)
			}
			if !strings.Contains(err.Error(), scenario.Message) {
				t.Fatalf("err.Error() = %q does not contain %q", err.Error(), scenario.Message)
			}
		}
	default:
		t.Fatalf("expect = %q, want accept or reject", scenario.Expect)
	}
}

func TestPostgresCollectorsAppsSearch1TriggerScenarios(t *testing.T) {
	t.Parallel()

	scenarios := cas1LoadScenarios(t)
	db := testsupport.NewPostgresControlDB(t)
	ran := 0
	for _, scenario := range scenarios {
		if len(scenario.DependsOnLanes) != 0 {
			continue
		}
		ran++
		// Sequential on purpose: four cases take ACCESS EXCLUSIVE locks with
		// ALTER TABLE ... DISABLE TRIGGER, and one database keeps the whole
		// fixture cheap.
		t.Run(scenario.Name, func(t *testing.T) {
			cas1RunScenario(t, db.SQLDB(), scenario)
		})
	}
	if ran == 0 {
		t.Fatal("no lane-local trigger scenarios ran")
	}
}

// TestPostgresCollectorsAppsSearch1CrossLaneTriggerScenarios runs the cases
// that hold only once other trigger lanes are installed. A case whose lanes
// are all in the embedded migration set must pass, so it fails loudly as soon
// as integration installs its dependencies and the outcome is wrong. A case
// whose lanes are still missing is logged as pending, never skipped, and the
// test fails if the fixture has cross-lane cases but none could be pending or
// run, which would mean the case list was lost.
func TestPostgresCollectorsAppsSearch1CrossLaneTriggerScenarios(t *testing.T) {
	t.Parallel()

	scenarios := cas1LoadScenarios(t)
	installed := cas1InstalledLanes(t)
	if !installed[cas1Lane] {
		t.Fatalf("embedded migrations lack %s; installed trigger lanes = %v", cas1MigrationFile, installed)
	}
	var runnable, pending []cas1Scenario
	for _, scenario := range scenarios {
		if len(scenario.DependsOnLanes) == 0 {
			continue
		}
		var missing []string
		for _, lane := range scenario.DependsOnLanes {
			if !installed[lane] {
				missing = append(missing, lane)
			}
		}
		if len(missing) != 0 {
			t.Logf("pending until trigger lanes %v are installed: %s", missing, scenario.Name)
			pending = append(pending, scenario)
			continue
		}
		runnable = append(runnable, scenario)
	}
	if len(runnable)+len(pending) == 0 {
		t.Fatal("the fixture has no cross-lane scenarios; drop this test only together with depends_on_lanes")
	}
	if len(runnable) == 0 {
		return
	}
	db := testsupport.NewPostgresControlDB(t)
	for _, scenario := range runnable {
		t.Run(scenario.Name, func(t *testing.T) {
			cas1RunScenario(t, db.SQLDB(), scenario)
		})
	}
}

// cas1Setup runs statements in one committed transaction with search_path
// pinned. SET LOCAL session_replication_role inside statements ends with it.
func cas1Setup(t *testing.T, db *control.PostgresDB, statements ...string) {
	t.Helper()
	ctx := t.Context()
	tx, err := db.SQLDB().BeginTx(ctx, nil)
	if err != nil {
		t.Fatalf("begin setup: %v", err)
	}
	committed := false
	defer func() {
		if !committed {
			_ = tx.Rollback()
		}
	}()
	for index, statement := range statements {
		if _, err := tx.ExecContext(ctx, statement); err != nil {
			t.Fatalf("setup statement %d failed: %v\n%s", index, err, statement)
		}
	}
	if err := tx.Commit(); err != nil {
		t.Fatalf("commit setup: %v", err)
	}
	committed = true
}

func cas1RequireRaise(t *testing.T, err error, want string) {
	t.Helper()
	if message, ok := control.RaiseMessage(err); !ok || message != want {
		t.Fatalf("error = %v, want RAISE %q", err, want)
	}
}

func cas1QueryInt64s(t *testing.T, db *control.PostgresDB, query string) []int64 {
	t.Helper()
	rows, err := db.SQLDB().QueryContext(t.Context(), query)
	if err != nil {
		t.Fatalf("query %q: %v", query, err)
	}
	columns, err := rows.Columns()
	if err != nil {
		_ = rows.Close()
		t.Fatalf("columns of %q: %v", query, err)
	}
	var values []int64
	for rows.Next() {
		row := make([]int64, len(columns))
		targets := make([]any, len(columns))
		for index := range row {
			targets[index] = &row[index]
		}
		if err := rows.Scan(targets...); err != nil {
			_ = rows.Close()
			t.Fatalf("scan %q: %v", query, err)
		}
		values = append(values, row...)
	}
	if err := errors.Join(rows.Err(), rows.Close()); err != nil {
		t.Fatalf("read %q: %v", query, err)
	}
	return values
}

