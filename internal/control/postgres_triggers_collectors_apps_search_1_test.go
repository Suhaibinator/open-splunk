// TestPostgresCollectorsAppsSearch1CollectorRuntimeGuardsAbortAtomically is
// the PostgreSQL counterpart of the collector_runtime trigger assertions in
// internal/collectorfleet/migration_test.go (saturated catalog revision,
// runtime count underflow, missing revision marker, backward lease
// generation): each rejected autocommit statement leaves the runtime row and
// the tenant's catalog revision exactly as they were.
func TestPostgresCollectorsAppsSearch1CollectorRuntimeGuardsAbortAtomically(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name        string
		catalogSQL  string
		statement   string
		message     string
		wantRuntime []int64
		wantCatalog []int64
	}{
		{
			name: "saturated revision rejects a runtime update",
			catalogSQL: fmt.Sprintf(`INSERT INTO collector_catalog_revisions (tenant_id, revision, fleet_count, runtime_count)
				VALUES ('t1', %d, 1, 1)`, int64(math.MaxInt64)),
			statement:   `UPDATE collector_runtime SET queued_bytes = 99 WHERE tenant_id = 't1' AND collector_id = 'c1'`,
			message:     "collector catalog revision exhausted",
			wantRuntime: []int64{0, 5, 5},
			wantCatalog: []int64{math.MaxInt64, 1, 1},
		},
		{
			name: "saturated revision rejects a runtime delete",
			catalogSQL: fmt.Sprintf(`INSERT INTO collector_catalog_revisions (tenant_id, revision, fleet_count, runtime_count)
				VALUES ('t1', %d, 1, 1)`, int64(math.MaxInt64)),
			statement:   `DELETE FROM collector_runtime WHERE tenant_id = 't1' AND collector_id = 'c1'`,
			message:     "collector catalog revision exhausted",
			wantRuntime: []int64{0, 5, 5},
			wantCatalog: []int64{math.MaxInt64, 1, 1},
		},
		{
			name: "runtime count underflow rejects a runtime delete",
			catalogSQL: `INSERT INTO collector_catalog_revisions (tenant_id, revision, fleet_count, runtime_count)
				VALUES ('t1', 2, 1, 0)`,
			statement:   `DELETE FROM collector_runtime WHERE tenant_id = 't1' AND collector_id = 'c1'`,
			message:     "collector catalog runtime count underflow",
			wantRuntime: []int64{0, 5, 5},
			wantCatalog: []int64{2, 1, 0},
		},
		{
			name:        "missing revision marker rejects a runtime update",
			statement:   `UPDATE collector_runtime SET queued_bytes = 99 WHERE tenant_id = 't1' AND collector_id = 'c1'`,
			message:     "collector catalog fleet/runtime revision is missing",
			wantRuntime: []int64{0, 5, 5},
		},
		{
			name: "backward lease generation is rejected",
			catalogSQL: `INSERT INTO collector_catalog_revisions (tenant_id, revision, fleet_count, runtime_count)
				VALUES ('t1', 2, 1, 1)`,
			statement:   `UPDATE collector_runtime SET lease_generation = lease_generation - 1 WHERE tenant_id = 't1' AND collector_id = 'c1'`,
			message:     "collector runtime revisions cannot move backward",
			wantRuntime: []int64{0, 5, 5},
			wantCatalog: []int64{2, 1, 1},
		},
		{
			name: "collector identity change is rejected",
			catalogSQL: `INSERT INTO collector_catalog_revisions (tenant_id, revision, fleet_count, runtime_count)
				VALUES ('t1', 2, 1, 1)`,
			statement:   `UPDATE collector_runtime SET collector_id = 'other' WHERE tenant_id = 't1' AND collector_id = 'c1'`,
			message:     "collector runtime identity is immutable",
			wantRuntime: []int64{0, 5, 5},
			wantCatalog: []int64{2, 1, 1},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()

			db := testsupport.NewPostgresControlDB(t)
			// Replica mode plants the fleet, catalog and runtime rows past
			// every trigger, including other lanes' counter triggers.
			setup := []string{cas1TenantSQL, `SET LOCAL session_replication_role = replica`, cas1FleetSQL}
			if test.catalogSQL != "" {
				setup = append(setup, test.catalogSQL)
			}
			cas1Setup(t, db, append(setup, cas1RuntimeSQL)...)

			_, err := db.SQLDB().ExecContext(t.Context(), test.statement)
			cas1RequireRaise(t, err, test.message)

			if got := cas1QueryInt64s(t, db, cas1RuntimeStateSQL); !slices.Equal(got, test.wantRuntime) {
				t.Fatalf("runtime (queued_bytes, telemetry_revision, lease_generation) = %v, want %v", got, test.wantRuntime)
			}
			if got := cas1QueryInt64s(t, db, cas1CatalogSQL); !slices.Equal(got, test.wantCatalog) {
				t.Fatalf("catalog (revision, fleet_count, runtime_count) = %v, want %v", got, test.wantCatalog)
			}
		})
	}
}

// TestPostgresCollectorsAppsSearch1AppDeletionGuards is the PostgreSQL
// counterpart of the direct-SQL assertions in internal/control/app_test.go
// TestAppCatalogLifecycle: an active app cannot be deleted, an archived app
// referenced by a saved search cannot be deleted, and once the reference is
// gone the delete succeeds and advances the tenant's app catalog revision.
func TestPostgresCollectorsAppsSearch1AppDeletionGuards(t *testing.T) {
	t.Parallel()

	db := testsupport.NewPostgresControlDB(t)
	ctx := t.Context()
	cas1Setup(t, db, cas1TenantSQL, cas1AppSQL)
	revisionSQL := `SELECT revision FROM app_catalog_revisions WHERE tenant_id = 't1'`
	if got := cas1QueryInt64s(t, db, revisionSQL); !slices.Equal(got, []int64{1}) {
		t.Fatalf("app catalog revision after the first app = %v, want [1]", got)
	}
	deleteSQL := `DELETE FROM app_workspaces WHERE app_id = '` + cas1AppID + `'`

	_, err := db.SQLDB().ExecContext(ctx, deleteSQL)
	cas1RequireRaise(t, err, "app workspace must be archived before deletion")

	if _, err := db.SQLDB().ExecContext(ctx, `
		UPDATE app_workspaces
		SET state = 'archived', archived_at_unix_micro = 2, updated_at_unix_micro = 2, version = version + 1
		WHERE app_id = '`+cas1AppID+`'`); err != nil {
		t.Fatalf("archive app: %v", err)
	}
	if got := cas1QueryInt64s(t, db, revisionSQL); !slices.Equal(got, []int64{2}) {
		t.Fatalf("app catalog revision after archiving = %v, want [2]", got)
	}

	// The saved search is planted in replica mode so the reference exists
	// regardless of the saved_searches triggers owned by another lane.
	cas1Setup(t, db,
		`SET LOCAL session_replication_role = replica`,
		`INSERT INTO saved_searches (
			saved_search_id, tenant_id, version, name, app_id, owner_id, sharing_scope,
			definition_proto, created_at_unix_micro, updated_at_unix_micro
		) VALUES ('saved_app_dependency', 't1', 1, 'dependency', '`+cas1AppID+`', 'owner', 1, '\x01'::bytea, 1, 1)`,
	)
	_, err = db.SQLDB().ExecContext(ctx, deleteSQL)
	cas1RequireRaise(t, err, "app workspace is referenced by saved searches")
	if got := cas1QueryInt64s(t, db, `SELECT count(*) FROM app_workspaces`); !slices.Equal(got, []int64{1}) {
		t.Fatalf("apps after the rejected delete = %v, want [1]", got)
	}

	cas1Setup(t, db,
		`SET LOCAL session_replication_role = replica`,
		`DELETE FROM saved_searches WHERE saved_search_id = 'saved_app_dependency'`,
	)
	result, err := db.SQLDB().ExecContext(ctx, deleteSQL)
	if err != nil {
		t.Fatalf("delete archived, unreferenced app: %v", err)
	}
	if affected, err := result.RowsAffected(); err != nil || affected != 1 {
		t.Fatalf("deleted apps = %d, %v; want 1", affected, err)
	}
	if got := cas1QueryInt64s(t, db, revisionSQL); !slices.Equal(got, []int64{3}) {
		t.Fatalf("app catalog revision after deleting = %v, want [3]", got)
	}
}

// cas1Barrier holds every party's first attempt until all parties have taken
// their snapshot, so their SERIALIZABLE transactions overlap.
type cas1Barrier struct {
	arrived sync.WaitGroup
	release chan struct{}
}

func newCas1Barrier(parties int) *cas1Barrier {
	barrier := &cas1Barrier{release: make(chan struct{})}
	barrier.arrived.Add(parties)
	go func() {
		barrier.arrived.Wait()
		close(barrier.release)
	}()
	return barrier
}

func (barrier *cas1Barrier) wait(ctx context.Context) error {
	barrier.arrived.Done()
	select {
	case <-barrier.release:
		return nil
	case <-ctx.Done():
		return ctx.Err()
	}
}

// cas1RaceWriteTx runs each statement in its own WriteTx concurrently. Each
// first attempt takes its snapshot and then waits at a barrier before running
// its statement, so the transactions always overlap and SERIALIZABLE must
// abort one whose check the other invalidates; WriteTx retries it against
// the committed winner. Waiting before the statement, not after, means a
// statement that blocks on the other's row or key lock cannot deadlock the
// barrier.
func cas1RaceWriteTx(t *testing.T, db *control.PostgresDB, statements ...string) []error {
	t.Helper()
	ctx, cancel := context.WithTimeout(t.Context(), time.Minute)
	defer cancel()
	barrier := newCas1Barrier(len(statements))
	errs := make([]error, len(statements))
	var group sync.WaitGroup
	for index, statement := range statements {
		group.Go(func() {
			var attempts atomic.Int32
			errs[index] = db.WriteTx(ctx, func(tx *sql.Tx) error {
				if attempts.Add(1) == 1 {
					// The first query fixes a SERIALIZABLE snapshot. Arrive
					// even when it failed, so the other party never waits.
					_, snapshotErr := tx.ExecContext(ctx, `SELECT 1`)
					if err := errors.Join(snapshotErr, barrier.wait(ctx)); err != nil {
						return err
					}
				}
				_, err := tx.ExecContext(ctx, statement)
				return err
			})
		})
	}
	group.Wait()
	return errs
}

// cas1OneWinner requires exactly one nil error and returns the loser's.
func cas1OneWinner(t *testing.T, errs []error) error {
	t.Helper()
	var losers []error
	for _, err := range errs {
		if err != nil {
			losers = append(losers, err)
		}
	}
	if len(losers) != 1 {
		t.Fatalf("concurrent errors = %v, want exactly one winner and one loser", errs)
	}
	return losers[0]
}

// TestPostgresCollectorsAppsSearch1ReadThenWriteTriggersSerialize checks the
// porting note that the read-then-write triggers rely on SERIALIZABLE: two
// overlapping WriteTx callers cannot both pass a check the other's write
// invalidates. SQLite got this from its database-wide write lock.
func TestPostgresCollectorsAppsSearch1ReadThenWriteTriggersSerialize(t *testing.T) {
	t.Parallel()

	dashboardSQL := func(id, appID string) string {
		return `INSERT INTO dashboards (
				dashboard_id, version, name, app_id, tenant_id, owner_id, sharing_scope,
				definition_proto, created_at_unix_micro, updated_at_unix_micro
			) VALUES ('` + id + `', 1, 'n-` + id + `', '` + appID + `', 't1', 'o1', 1, '\x00'::bytea, 1, 1)`
	}

	t.Run("dashboard owner capacity", func(t *testing.T) {
		t.Parallel()
		db := testsupport.NewPostgresControlDB(t)
		cas1Setup(t, db, cas1TenantSQL, cas1AppSQL, `
			INSERT INTO dashboards (
				dashboard_id, version, name, app_id, tenant_id, owner_id, sharing_scope,
				definition_proto, created_at_unix_micro, updated_at_unix_micro
			)
			SELECT 'bulk' || g, 1, 'bulk' || g, '`+cas1AppID+`', 't1', 'o1', 1, '\x00'::bytea, 1, 1
			FROM generate_series(1, 63) AS g`)

		loser := cas1OneWinner(t, cas1RaceWriteTx(t, db,
			dashboardSQL("race-a", cas1AppID),
			dashboardSQL("race-b", cas1AppID),
		))
		cas1RequireRaise(t, loser, "dashboard owner capacity exhausted")
		if got := cas1QueryInt64s(t, db, `SELECT count(*) FROM dashboards WHERE tenant_id = 't1' AND owner_id = 'o1'`); !slices.Equal(got, []int64{64}) {
			t.Fatalf("dashboards for the owner = %v, want [64]", got)
		}
	})

	t.Run("app deletion against a new dashboard", func(t *testing.T) {
		t.Parallel()
		db := testsupport.NewPostgresControlDB(t)
		cas1Setup(t, db, cas1TenantSQL, cas1AppSQL, `
			UPDATE app_workspaces
			SET state = 'archived', archived_at_unix_micro = 2, updated_at_unix_micro = 2, version = version + 1
			WHERE app_id = '`+cas1AppID+`'`)

		errs := cas1RaceWriteTx(t, db,
			`DELETE FROM app_workspaces WHERE app_id = '`+cas1AppID+`'`,
			dashboardSQL("race-dashboard", cas1AppID),
		)
		loser := cas1OneWinner(t, errs)
		apps := cas1QueryInt64s(t, db, `SELECT count(*) FROM app_workspaces WHERE app_id = '`+cas1AppID+`'`)
		dashboards := cas1QueryInt64s(t, db, `SELECT count(*) FROM dashboards WHERE app_id = '`+cas1AppID+`'`)
		if errs[0] == nil {
			// The delete won: the dashboard's retry finds no app.
			cas1RequireRaise(t, loser, "canonical dashboard app does not exist")
			if !slices.Equal(apps, []int64{0}) || !slices.Equal(dashboards, []int64{0}) {
				t.Fatalf("after the delete won: apps = %v, dashboards = %v, want [0] and [0]", apps, dashboards)
			}
		} else {
			// The dashboard won: the delete's retry finds the reference.
			cas1RequireRaise(t, loser, "app is referenced by a dashboard")
			if !slices.Equal(apps, []int64{1}) || !slices.Equal(dashboards, []int64{1}) {
				t.Fatalf("after the dashboard won: apps = %v, dashboards = %v, want [1] and [1]", apps, dashboards)
			}
		}
	})

	t.Run("first app bootstraps one authority", func(t *testing.T) {
		t.Parallel()
		db := testsupport.NewPostgresControlDB(t)
		cas1Setup(t, db, cas1TenantSQL)
		appSQL := func(id, slug string) string {
			return `INSERT INTO app_workspaces (
					app_id, tenant_id, version, slug, display_name, default_time_range_present, state,
					created_at_unix_micro, updated_at_unix_micro, archived_at_unix_micro
				) VALUES ('` + id + `', 't1', 1, '` + slug + `', 'App', 0, 'active', 1, 1, NULL)`
		}
		errs := cas1RaceWriteTx(t, db,
			appSQL("app_bbbbbbbbbbbbbbbbbbbbbA", "first"),
			appSQL("app_cccccccccccccccccccccA", "second"),
		)
		for index, err := range errs {
			if err != nil {
				t.Fatalf("concurrent first app %d: %v", index, err)
			}
		}
		if got := cas1QueryInt64s(t, db, `SELECT revision FROM app_catalog_revisions WHERE tenant_id = 't1'`); !slices.Equal(got, []int64{2}) {
			t.Fatalf("app catalog revision after two first apps = %v, want [2]", got)
		}
	})
}
